"""
Sweep reliability-aware temporal detector/tracker merge rules.

This script is intentionally post-hoc: it consumes detector and tracker COCO
prediction JSON files that were already generated by inference.  Merge decisions
do not use GT; GT is only used for evaluation during the sweep.

Reliability score:

    R_det = detector_score
            + detector_bias
            - temporal_weight * detector_temporal_jump

    R_trk = tracker_score
            + tracker_bias
            - distance_penalty * distance_to_seed
            - temporal_weight * tracker_temporal_jump

When both candidates pass thresholds, tracker is selected if
R_trk > R_det + margin.  The detector/tracker mask IoU is logged as an
agreement feature and can be used as an optional disagreement gate.
"""

